#include "mesh_exporter.h"
#include <fstream>
#include <iomanip>

bool ExportModelToOBJ(const ModelAsset& asset, const std::string& modelDir) {
	const std::string objPath = modelDir + "/" + asset.modelName + ".obj";
	const std::string mtlName = asset.modelName + ".mtl";
	const std::string mtlPath = modelDir + "/" + mtlName;

	// 1. Tulis file .mtl
	std::ofstream mtl(mtlPath);
	if (!mtl.is_open()) return false;
	mtl << "# Generated by Angry Capibara VS Asset Forge\n";
	mtl << std::fixed << std::setprecision(4);

	for (const auto& mat : asset.materials) {
		mtl << "newmtl " << mat.name << "\n";
		mtl << "Ka 0.2000 0.2000 0.2000\n";
		mtl << "Kd " << mat.kd.r << " " << mat.kd.g << " " << mat.kd.b << "\n";
		mtl << "Ks " << mat.ks.r << " " << mat.ks.g << " " << mat.ks.b << "\n";
		if (glm::length(mat.ke) > 1e-4f) {
			mtl << "Ke " << mat.ke.r << " " << mat.ke.g << " " << mat.ke.b << "\n";
		}
		mtl << "Ns " << mat.shininess << "\n";
		mtl << "d 1.0000\n";
		if (!mat.textureFile.empty()) {
			mtl << "map_Kd ../textures/" << mat.textureFile << "\n";
		}
		mtl << "\n";
	}
	mtl.close();

	// 2. Tulis file .obj
	std::ofstream obj(objPath);
	if (!obj.is_open()) return false;
	obj << "# Generated by Angry Capibara VS Asset Forge\n";
	obj << "mtllib " << mtlName << "\n";
	obj << std::fixed << std::setprecision(6);

	uint32_t vOffset = 1;
	for (const auto& part : asset.parts) {
		if (part.vertices.empty() || part.indices.empty()) continue;
		obj << "o " << part.objectName << "\n";
		for (const auto& v : part.vertices) {
			obj << "v " << v.pos.x << " " << v.pos.y << " " << v.pos.z << "\n";
		}
		for (const auto& v : part.vertices) {
			obj << "vt " << v.uv.x << " " << v.uv.y << "\n";
		}
		for (const auto& v : part.vertices) {
			obj << "vn " << v.normal.x << " " << v.normal.y << " " << v.normal.z << "\n";
		}
		obj << "usemtl " << part.materialName << "\n";
		obj << "s 1\n";

		for (size_t i = 0; i + 2 < part.indices.size(); i += 3) {
			uint32_t a = vOffset + part.indices[i];
			uint32_t b = vOffset + part.indices[i + 1];
			uint32_t c = vOffset + part.indices[i + 2];
			obj << "f " << a << "/" << a << "/" << a << " "
				<< b << "/" << b << "/" << b << " "
				<< c << "/" << c << "/" << c << "\n";
		}
		vOffset += static_cast<uint32_t>(part.vertices.size());
	}

	return obj.good();
}
